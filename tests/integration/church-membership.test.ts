import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { after, test } from 'node:test';
import { PrismaPg } from '@prisma/adapter-pg';
import { PrismaClient } from '@daegwang/database/generated/client';
import { createChurchMembershipService, reviewChurchMembership, requestChurchOnSignup } from '@daegwang/server/features/member/church-membership';
const url = new URL(process.env.TEST_DATABASE_URL ?? 'http://invalid');
if (url.hostname !== '127.0.0.1' || url.pathname !== '/daegwang_worship_test') throw new Error('Isolated local test database required');
const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: url.href }) });
after(async () => db.$disconnect());
test('signup confirmation creates one pending request and never overwrites a reviewed member', async () => {
  const ownerId = randomUUID(); const details = { realName: 'Fixture', phone: '010-1234-5678', position: '없음' };
  await db.memberProfile.create({ data: { ownerId } });
  await db.$transaction(tx => requestChurchOnSignup(tx, ownerId, details));
  await db.churchMembership.update({ where: { ownerId }, data: { status: 'CONFIRMED' } });
  await db.$transaction(tx => requestChurchOnSignup(tx, ownerId, { ...details, realName: 'Changed' }));
  const row = await db.churchMembership.findUniqueOrThrow({ where: { ownerId } });
  assert.equal(row.status, 'CONFIRMED'); assert.equal(row.realName, details.realName); assert.equal(row.phone, details.phone);
});
test('church confirmation requires a real request and super admin; stale edits, forged self-approval and other owners cannot change it', async () => {
  const owner = randomUUID(); const other = randomUUID();
  const service = createChurchMembershipService(db, owner);
  const admin = await db.adminProfile.create({ data: { authUserId: randomUUID(), email: `${randomUUID()}@example.invalid`, displayName: 'Fixture', role: 'SUPER_ADMIN' } });
  assert.equal((await service.detail()).status, 'UNCONFIRMED');
  await assert.rejects(service.request({ realName: 'Fixture', phone: '010-1234-5678', position: '성도', version: 0, status: 'CONFIRMED' }));
  const pending = await service.request({ realName: 'Fixture', phone: '010-1234-5678', position: '성도', version: 0 });
  assert.equal(pending.status, 'PENDING');
  assert.equal((await createChurchMembershipService(db, other).detail()).status, 'UNCONFIRMED');
  await assert.rejects(reviewChurchMembership(db, 'invalid-admin', { ownerId: owner, version: 1, status: 'CONFIRMED' }));
  const group = await db.churchGroup.create({ data: { id: `fixture-${randomUUID()}`, name: 'Fixture group' } });
  await assert.rejects(reviewChurchMembership(db, admin.id, { ownerId: owner, version: 1, status: 'CONFIRMED', groupIds: ['missing-group'] }));
  assert.equal((await service.detail()).status, 'PENDING');
  await reviewChurchMembership(db, admin.id, { ownerId: owner, version: 1, status: 'CONFIRMED', groupIds: [group.id] });
  assert.equal((await service.detail()).groups[0].id, group.id);
  assert.equal((await service.detail()).status, 'CONFIRMED');
  await assert.rejects(service.request({ realName: 'Fixture', phone: '010-1234-5678', position: '성도', version: 2 }));
  await assert.rejects(reviewChurchMembership(db, admin.id, { ownerId: owner, version: 1, status: 'UNCONFIRMED' }));
  await reviewChurchMembership(db, admin.id, { ownerId: owner, version: 2, status: 'UNCONFIRMED' });
  assert.equal((await service.detail()).status, 'UNCONFIRMED');
  assert.equal(await db.groupMembership.count({ where: { ownerId: owner } }), 0);
  await db.memberProfile.delete({ where: { ownerId: owner } });
  assert.equal(await db.churchMembership.findUnique({ where: { ownerId: owner } }), null);
});
