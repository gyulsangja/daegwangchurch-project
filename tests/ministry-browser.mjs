import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { chromium } from '@playwright/test';

const base = 'http://127.0.0.1:3002';
const browser = await chromium.launch({ channel: process.env.TEST_BROWSER_CHANNEL || 'msedge', headless: true });
mkdirSync('test-results/ministry', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base); await page.getByRole('heading', { name: '우리 교회를 한눈에' }).waitFor();
  await page.screenshot({ path: 'test-results/ministry/home-desktop.png', fullPage: true, caret: 'initial' });
  await page.goto(`${base}/members`);
  await page.getByRole('textbox', { name: '이름', exact: true }).fill('가람');
  await page.getByRole('button', { name: '검색', exact: true }).click();
  await page.waitForURL(url => url.pathname === '/members' && url.searchParams.get('q') === '가람');
  await page.getByRole('link', { name: /가상교인 가람/ }).click();
  await page.getByRole('button', { name: '가족', exact: true }).click();
  await page.getByText('가람·나래 가정 (예시)').waitFor();
  await page.getByRole('link', { name: '← 교인 목록' }).click();
  await page.waitForURL(url => url.pathname === '/members');
  assert.equal(new URL(page.url()).searchParams.get('q'), '가람');
  await page.goto(`${base}/members/new`);
  const name = `가상검증-${Date.now()}`;
  await page.getByRole('textbox', { name: /이름/ }).fill(name);
  await page.getByRole('checkbox', { name: '청년 모임 (예시)' }).check();
  await page.getByRole('checkbox', { name: '찬양 봉사 (예시)' }).check();
  await page.getByRole('button', { name: '교인 등록', exact: true }).click();
  await page.getByRole('heading', { name, exact: true }).waitFor();
  const memberId = new URL(page.url()).pathname.split('/').at(-1);
  await page.getByRole('link', { name: '정보 수정' }).click();
  await page.getByRole('textbox', { name: /이름/ }).fill(`${name}-수정`);
  await page.getByRole('button', { name: '변경 저장' }).click();
  await page.getByRole('heading', { name: `${name}-수정`, exact: true }).waitFor();
  await page.getByRole('button', { name: '변경 이력', exact: true }).click();
  await page.getByText('정보 수정', { exact: true }).last().waitFor();
  const data = { name, status: 'ACTIVE', position: '', phone: '', address: '', organizationIds: [], version: 1 };
  const stale = await page.request.patch(`${base}/api/v1/members/${memberId}`, { data, headers: { Origin: base } });
  assert.equal(stale.status(), 409);
  const foreign = await page.request.post(`${base}/api/v1/members`, { data, headers: { Origin: 'https://outside.example' } });
  assert.equal(foreign.status(), 403);
  const forged = await page.request.post(`${base}/api/v1/members`, { data: { name, status: 'ACTIVE', churchId: 'demo-other' }, headers: { Origin: base } });
  assert.equal(forged.status(), 422);
  const oversized = await page.request.post(`${base}/api/v1/members`, { data: { name: 'x'.repeat(20000), status: 'ACTIVE' }, headers: { Origin: base } });
  assert.equal(oversized.status(), 413);
  const external = await page.request.get(`${base}/api/v1/members`, { headers: { Host: 'outside.example:3002' } });
  assert.equal(external.status(), 503);
  await page.goto(`${base}/members`);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/ministry/members-mobile.png', fullPage: true, caret: 'initial' });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile document should not overflow');
  await page.goto(`${base}/members/new`);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: 'test-results/ministry/member-new-mobile.png', fullPage: true, caret: 'initial' });
  assert.deepEqual(errors, []);
  console.log('Passed: navigation/filter preservation, family display, create/edit/history, conflict, origin/host/body guards, mobile width, browser runtime.');
} finally { await browser.close(); }
