import assert from 'node:assert/strict';
import {chromium} from '@playwright/test';
const base='http://127.0.0.1:3002';
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`${base}/settings`);
  await page.getByRole('button',{name:'조직 구성',exact:true}).click();
  await page.getByRole('button',{name:'조직 추가',exact:true}).click();
  const org=page.locator('.org-edit').last();
  await org.getByLabel('조직 이름').fill('교회학교 검증');
  await org.getByRole('combobox',{name:'유형',exact:true}).selectOption('SCHOOL');
  await page.getByRole('button',{name:'체계 저장',exact:true}).click();
  await page.waitForURL(url=>url.searchParams.get('tab')==='조직 구성');
  await page.getByRole('button',{name:'구성원 배정',exact:true}).click();
  await page.getByLabel('교인 선택').selectOption('demo-member-1');
  await page.getByRole('checkbox',{name:'교회학교 검증'}).check();
  await page.locator('.assignment-row').filter({hasText:'교회학교 검증'}).getByLabel('역할').selectOption('TEACHER');
  await page.getByRole('button',{name:'배정 저장',exact:true}).click();
  await page.waitForURL(url=>url.searchParams.get('tab')==='구성원 배정');
  await page.screenshot({path:'test-results/ministry/annual-desktop.png',fullPage:true,caret:'initial'});
  await page.goto(`${base}/members/demo-member-1`);
  await page.getByRole('button',{name:'출석',exact:true}).click();
  await page.getByText('출석 추가',{exact:true}).click();
  await page.getByLabel('발생일',{exact:true}).fill('2026-10-18');
  await page.getByLabel('예배·모임 이름').fill('주일 오전예배');
  await page.getByRole('button',{name:'기록 저장',exact:true}).click();
  await page.waitForEvent('load');
  await page.getByRole('button',{name:'출석',exact:true}).click();
  await page.getByText('2026-10-18 · 교회 전체 · 주일 오전예배 · 출석',{exact:true}).waitFor();
  await page.getByRole('button',{name:'상담·심방',exact:true}).click();
  await page.getByText('상담·심방 추가',{exact:true}).click();
  await page.getByLabel('상담 내용',{exact:true}).fill('가상 상담 내용 (검증 자료)');
  await page.getByRole('button',{name:'기록 저장',exact:true}).click();
  await page.waitForEvent('load');
  await page.getByRole('button',{name:'상담·심방',exact:true}).click();
  await page.getByText('가상 상담 내용 (검증 자료)',{exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'test-results/ministry/records-mobile.png',fullPage:true,caret:'initial'});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.goto(`${base}/settings`);
  await page.getByRole('button',{name:'조직 구성',exact:true}).click();
  await page.screenshot({path:'test-results/ministry/annual-mobile.png',fullPage:true,caret:'initial'});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(errors,[]);
  console.log('Annual organization/teacher assignment, attendance/care save, responsive widths passed.');
} finally {await browser.close();}
